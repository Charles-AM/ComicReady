import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { reviewedCatalog } from '../src/lib/catalog.ts';

const output = fileURLToPath(new URL('../supabase/migrations/202610030001_catalog_expansion.sql', import.meta.url));

function stableUuid(value) {
  const bytes = createHash('sha256').update(`comicready:${value}`).digest().subarray(0, 16);
  bytes[6] = (bytes[6] & 0x0f) | 0x50;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = bytes.toString('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

const catalog = reviewedCatalog.map((call) => {
  if (call.fixture || !call.last_verified_at || !call.official_url.startsWith('https://')) {
    throw new Error(`Reviewed catalog entry ${call.slug} is missing trustworthy source metadata.`);
  }
  const opportunityId = stableUuid(`opportunity:${call.slug}`);
  return {
    ...call,
    id: opportunityId,
    requirements: call.requirements.map((requirement) => {
      if (!requirement.source_url.startsWith('https://')) {
        throw new Error(`Requirement ${requirement.id} does not use an HTTPS official source.`);
      }
      return {
        ...requirement,
        id: stableUuid(`requirement:${call.slug}:${requirement.id}`),
        opportunity_id: opportunityId,
      };
    }),
  };
});

const json = JSON.stringify(catalog, null, 2);
if (json.includes('$catalog$')) throw new Error('Catalog data conflicts with the SQL dollar-quote marker.');

const sql = `-- Generated by scripts/generate-reviewed-catalog-migration.mjs.
-- Every row below comes from a manually reviewed official source in src/lib/catalog.ts.
-- Re-running this migration content is safe: calls are matched by slug and rules are replaced atomically.
do $migration$
declare
  catalog jsonb := $catalog$${json}$catalog$::jsonb;
  opportunity jsonb;
  requirement jsonb;
  stored_opportunity_id uuid;
begin
  for opportunity in select value from jsonb_array_elements(catalog)
  loop
    insert into public.opportunities (
      id, slug, title, organizer, category, official_url, status, deadline,
      deadline_timezone, deadline_note, deadline_date, compensation,
      compensation_type, region_scope, rights_disclosure, last_verified_at,
      published, description, roles, formats, updated_at
    ) values (
      (opportunity->>'id')::uuid,
      opportunity->>'slug',
      opportunity->>'title',
      opportunity->>'organizer',
      opportunity->>'category',
      opportunity->>'official_url',
      opportunity->>'status',
      nullif(opportunity->>'deadline', '')::timestamptz,
      nullif(opportunity->>'deadline_timezone', ''),
      nullif(opportunity->>'deadline_note', ''),
      nullif(opportunity->>'deadline_date', '')::date,
      nullif(opportunity->>'compensation', ''),
      opportunity->>'compensation_type',
      opportunity->>'region_scope',
      nullif(opportunity->>'rights_disclosure', ''),
      (opportunity->>'last_verified_at')::timestamptz,
      true,
      opportunity->>'description',
      array(select jsonb_array_elements_text(opportunity->'roles')),
      array(select jsonb_array_elements_text(opportunity->'formats')),
      (opportunity->>'last_verified_at')::timestamptz
    )
    on conflict (slug) do update set
      title = excluded.title,
      organizer = excluded.organizer,
      category = excluded.category,
      official_url = excluded.official_url,
      status = excluded.status,
      deadline = excluded.deadline,
      deadline_timezone = excluded.deadline_timezone,
      deadline_note = excluded.deadline_note,
      deadline_date = excluded.deadline_date,
      compensation = excluded.compensation,
      compensation_type = excluded.compensation_type,
      region_scope = excluded.region_scope,
      rights_disclosure = excluded.rights_disclosure,
      last_verified_at = excluded.last_verified_at,
      published = true,
      description = excluded.description,
      roles = excluded.roles,
      formats = excluded.formats,
      updated_at = excluded.updated_at
    returning id into stored_opportunity_id;

    delete from public.requirements where requirements.opportunity_id = stored_opportunity_id;
    for requirement in select value from jsonb_array_elements(opportunity->'requirements')
    loop
      insert into public.requirements (
        id, opportunity_id, kind, roles, formats, field, operator, value,
        wording, source_reference, source_url
      ) values (
        (requirement->>'id')::uuid,
        stored_opportunity_id,
        requirement->>'kind',
        array(select jsonb_array_elements_text(requirement->'roles')),
        array(select jsonb_array_elements_text(requirement->'formats')),
        nullif(requirement->>'field', ''),
        requirement->>'operator',
        nullif(requirement->'value', 'null'::jsonb),
        requirement->>'wording',
        requirement->>'source_reference',
        requirement->>'source_url'
      );
    end loop;

    if not exists (
      select 1 from public.verification_events
      where verification_events.opportunity_id = stored_opportunity_id
        and result = 'verified'
        and checked_at = (opportunity->>'last_verified_at')::timestamptz
    ) then
      insert into public.verification_events (
        opportunity_id, checked_at, result, admin_note, checked_by
      ) values (
        stored_opportunity_id,
        (opportunity->>'last_verified_at')::timestamptz,
        'verified',
        'Imported from the reviewed ComicReady catalog. Official source and structured requirements were manually checked.',
        null
      );
    end if;
  end loop;
end
$migration$;
`;

await writeFile(output, sql);
console.log(`Wrote ${catalog.length} reviewed calls to ${output}`);
